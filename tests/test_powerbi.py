"""The Power BI project is generated, mirrors Cube, and only references real fields."""

import importlib.util
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
POWERBI = ROOT / "powerbi"


def load(name: str, path: Path) -> Any:
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


build_pbip = load("build_pbip", POWERBI / "build_pbip.py")
validate_pbip = load("validate_pbip", POWERBI / "scripts" / "validate_pbip.py")


def cube_measures() -> dict[str, set[str]]:
    measures: dict[str, set[str]] = {}
    for path in (ROOT / "semantic" / "model" / "cubes").glob("*.yml"):
        for cube in yaml.safe_load(path.read_text())["cubes"]:
            measures[cube["name"]] = {m["name"] for m in cube.get("measures", [])}
    return measures


def test_committed_project_matches_the_generator() -> None:
    for path, text in build_pbip.render_all().items():
        assert path.exists(), f"{path} missing; run `make powerbi`"
        assert path.read_text() == text, f"{path} is stale; run `make powerbi`"


def test_no_stale_generated_files() -> None:
    expected = set(build_pbip.render_all())
    for folder in ("Dockline.SemanticModel", "Dockline.Report"):
        for path in (POWERBI / folder).rglob("*"):
            if path.is_file() and ".pbi" not in path.parts:
                assert path in expected, f"{path} is not generated by build_pbip.py"


def test_dax_measures_mirror_cube_measures_by_name() -> None:
    cubes = cube_measures()
    for table in build_pbip.TABLES:
        if not table.measures:
            continue
        assert table.cube in cubes, table.name
        for measure in table.measures:
            if measure.hidden:
                continue  # helpers such as usable_slots are not certified metrics
            assert measure.name in cubes[table.cube], (
                f"{table.name}.{measure.name} has no Cube twin"
            )


def test_catalog_metrics_available_in_power_bi() -> None:
    names = {m.name for table in build_pbip.TABLES for m in table.measures}
    assert {
        "bikes_available",
        "ebikes_available",
        "docks_available",
        "fill_ratio",
        "imbalance_index",
        "empty_station_minutes",
        "full_station_minutes",
        "availability_rate",
        "net_flow",
        "rebalance_need_bikes",
        "chronic_problem_stations",
        "data_freshness_seconds",
    } <= names


def test_measure_names_are_unique_and_never_collide_with_columns() -> None:
    measures = [m.name for table in build_pbip.TABLES for m in table.measures]
    assert len(measures) == len(set(measures))
    for table in build_pbip.TABLES:
        column_names = {c.name for c in table.columns}
        assert not column_names & {m.name for m in table.measures}, table.name


def test_every_measure_has_a_folder_format_and_description() -> None:
    for table in build_pbip.TABLES:
        for measure in table.measures:
            assert measure.folder and measure.format_string and measure.description, measure.name


def test_rls_role_per_borough_filters_the_borough_table() -> None:
    roles = sorted((POWERBI / "Dockline.SemanticModel" / "definition" / "roles").glob("*.tmdl"))
    assert len(roles) == len(build_pbip.BOROUGHS)
    for path in roles:
        assert "tablePermission Borough = [borough] = " in path.read_text()


def test_directquery_parameters_and_date_table() -> None:
    expressions = (
        POWERBI / "Dockline.SemanticModel" / "definition" / "expressions.tmdl"
    ).read_text()
    for parameter in ("DbHost", "DbPort", "DbName"):
        assert f"expression {parameter} = " in expressions
    date_table = (
        POWERBI / "Dockline.SemanticModel" / "definition" / "tables" / "Date.tmdl"
    ).read_text()
    assert "dataCategory: Time" in date_table and "isKey" in date_table
    for path in (POWERBI / "Dockline.SemanticModel" / "definition" / "tables").glob("*.tmdl"):
        assert "mode: directQuery" in path.read_text()


def test_five_pages_with_auto_refresh_on_live_operations() -> None:
    names = [page.display_name for page in build_pbip.PAGES]
    assert names == [
        "Executive Summary",
        "Live Operations",
        "Station Performance",
        "Weather Impact",
        "Rebalancing",
    ]
    live = next(page for page in build_pbip.PAGES if page.key == "live")
    assert live.refresh_seconds is not None


def test_every_report_field_exists_in_the_model() -> None:
    errors, count = validate_pbip.check_fields()
    assert count > 50
    assert errors == []
    assert validate_pbip.check_model_references() == []


